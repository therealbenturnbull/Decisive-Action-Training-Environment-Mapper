  const schemesById = new Map(schemes.map((scheme) => [scheme.id, scheme]));

  function normalizeId(value) {
    const id = String(value || "").trim().toLowerCase();
    return schemesById.has(id) ? id : "basic";
  }

  function get(value) {
    return schemesById.get(normalizeId(value));
  }

  function stableColourIndex(value) {
    const seed = String(value || "");
    let hash = 0;
    for (let index = 0; index < seed.length; index += 1) {
      hash = ((hash << 5) - hash + seed.charCodeAt(index)) | 0;
    }
    return Math.abs(hash) % naturalLandColours.length;
  }

  function countryFill(schemeId, country, surface) {
    const palette = get(schemeId)[surface];
    const isDateDataset = Boolean(country?.isDateDataset ?? country?.is_date_dataset);
    if (isDateDataset && palette.dateCountryFill) {
      return palette.dateCountryFill;
    }
    if (palette.countryFill === "natural") {
      return naturalLandColours[stableColourIndex(country?.key || country?.id || country?.name)];
    }
    return palette.countryFill;
  }

  function countryStroke(schemeId, country, surface) {
    const palette = get(schemeId)[surface];
    const isDateDataset = Boolean(country?.isDateDataset ?? country?.is_date_dataset);
    return isDateDataset && palette.dateCountryStroke
      ? palette.dateCountryStroke
      : palette.countryStroke;
  }

  window.DateMapperColourSchemes = Object.freeze({
    all: () => schemes,
    countryFill,
    countryStroke,
    get,
    normalizeId,
  });
